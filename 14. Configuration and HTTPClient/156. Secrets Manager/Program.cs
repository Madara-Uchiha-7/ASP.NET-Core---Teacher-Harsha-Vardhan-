/*
If you really stored the important sensitive information in these configuration files
such as client id or client secret or passwords or any other sensitive information
and also you will push the source code into the source control such as github.
Then the sensitive information that you have stored in this configuration will be revealed to other developers.
So it is not good.

It should be stored locally outside the source code of the project.
So the solution for this problem for Microsoft is the secret manager.

In .NET Core, you can use the secret manager
in order to store the sensitive information in the configuration
outside the source code of the project.

But how does the secrets manager help us to store the sensitive information outside the source code?
You have to enable the secrets manager with this .NET command
dotnet user-secrets init
dotnet user-secrets set "Key" "Value"
dotnet user-secrets list

Then these key value pairs will be stored in a separate different location on the developer machine.
It is one for one developer machine.
It will be stored in the app data folder on Windows.
So in that way, the sensitive information will not be stored in the configuration file
as a part of the source code, but it will be stored outside the source code.
So it will not be pushed into the source control.

In that way, the sensitive information will be stored on the same developer machine.
It is not revealed to the other developers.

For working with these commands, either you can use Windows PowerShell
or developer PowerShell window in Visual Studio itself.

In this case, I'm using developer PowerShell.
So in Visual Studio, go to the View menu and say Terminal.
You can use the keyboard shortcut Ctrl + `


Once it opens up this developer PowerShell below, it by default locates the current working solution folder.
But we have to locate the project folder where your csproj file is present.
Use "cd projectName" command to go inside the project folder.

Then use above commands one by one:
dotnet user-secrets init
(
When you run above command, it will
it will automatically generates a hexadecimal code as user secret id.
And with that name, a JSON file will be created.
Means the hexadecimal code .json that will be stored in the app data folder.
And that user secret id will be stored as a part of this csproj file
in the current working ASP.NET core project.
)

When I ran this command I got:
Set UserSecretsId to '2ccdd764-cd74-4108-80b7-7a7c49e64cf0' 
for 
MSBuild project 
'D:\Code\Udemy\ASP .NET Core - Harsha Vardhan\14. Configuration and HTTPClient\156. Secrets Manager\156. Secrets Manager.csproj'.

Double click on your Project, you will see the <UserSecretsId> with the above id in it.
Right click on the Project folder, click on Manage User Secrets 
It will open newly created hashcode/secrets.json
It will be in C:\Users\Your_User_Name\AppData\Roaming\Microsoft\UserSecrets\your_hash_code\secrets.json

Do not edit this file directly.

Now run:
dotnet user-secrets set "WeatherApi:ClinetID" "678910"   
After above command you will get a success message. 

Now run:
dotnet user-secrets set "WeatherApi:ClinetSecret" "EUEUEUEU" 

Now run below command to see the added key value pairs:
dotnet user-secrets list

I have not addded the same code as last projects. But the code will work fine once you add it.

This user-secrets only works in development environment.

But in case if your project is being maintained on the cloud in Microsoft Azure,
you can use the Azure Key Vault for better security.

