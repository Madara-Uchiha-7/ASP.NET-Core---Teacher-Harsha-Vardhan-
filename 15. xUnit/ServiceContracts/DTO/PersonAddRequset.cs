    /// -------------------------------- Start 174. Add Person - Model - 1 -----------------------------------
    /// 
    /// <summary>
    /// Acts a DTO for inserting a new Person 
    /// </summary>
    public class PersonAddRequset
    {
        // The DomainModel class contains all the properties that
        // you would like to store in the database table, but this DTO class should contain only
        // the properties which are entered by the user, irrespective of the database data.
        // In our application, the PersonAddRequest contains all the details except PersonID.
        // Because the ID will be generated by us, not the User.
        // We have added the ?, this means the value of the property can be null.
        // If you want to make the property mandetory, remove this ?
        // If you remove the ?, make sure that you
        // initialize that property within the constructor or inline initialization within the property declaration itself.
        public string? Name { get; set; }
        public string? Email { get; set; }
        public DateTime? DateOfBirth { get; set; }
        public GenderOptions? Gender { get; set; }
        public Guid? CountryID { get; set; }
        public string? Address { get; set; }
        public bool ReceiveNewsLetters { get; set; }

        /// -------------------------------- Start 175. Add Person - Model - 2 -----------------------------------
        ///
        // We are going to add the method here.
        public Person ToPerson()
        {
            // So we have to convert an object of the person
            // add request into person type while adding it to the datastore. So there we will call this
            // ToPerson method. Here we are going to create and return a new object of the Person class,
            // which includes with the PersonId. Okay, PersonId is not available in this property.
            return new Person() 
            { 
                Name = Name,
                Email = Email,
                DateOfBirth = DateOfBirth,
                Gender = Gender.ToString(),
                Address = Address,
                CountryID = CountryID,
                ReceiveNewsLetters = ReceiveNewsLetters
            };
        }
        /// -------------------------------- End 175. Add Person - Model - 2 -----------------------------------
        ///

    }
    /// -------------------------------- End of 174. Add Person - Model - 1 -----------------------------------
