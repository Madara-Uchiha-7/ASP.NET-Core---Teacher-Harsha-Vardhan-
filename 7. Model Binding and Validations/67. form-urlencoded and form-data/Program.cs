// We are going to talk about the Form Field which is present at the top of the Model Binding.
// Generally we use this form fields when you click on submit button in a HTML form.
// Suppose there is some registration form with text boxes like name, date of etc.
// and after entering the values for all of them if you click on submit button then all those
// values which you enter in the text boxes will be submitted to the server and those are called
// form fields.

// Generally the values are added in the request body in either of the two formats, that is either
// form URL encoded or form data. Whereas the first one is the simple one but form data is
// a complex one. In case of form URL encoded, in the request headers the content type will be added as a
// predefined and fixed name that is application by x-www-form-urlencoded. It is the predefined fixed name
// to identify this form URL encoded format. That means it is as simple as in the request body you
// can add the query string details instead of in the URL. So you can understand this as in case of GET request this
// query string will be a part of the URL which we have been doing till now in last lectures either from
// browser or from postman, but in case of POST request particularly in case of form URL encoded the same
// query string can be added in the request body but form data is a bit complex one.

// Use the postman. To run the postman you first need to run this application.
// Paste the URL in postman. In the params tab you can add a query string parameters, but this tab is 
// for GET request. Headers tab is for to add any request headers but the point of interest for us is request body,
// so go to the Body tab. Select "x-www-form-urlencoded" (This will be the content-type)
// You can pass the query string parameters here in key
// value format e.g. keys wuill be bookid and isloggedin and the values will be
// 20 and true. The keys are not case-sensitive.
// Now when you hit enter or send the request using Postman POST action. You will reveive the data in the 
// parameter of Action Method in the model object. That data will be coming from the Form Fields.
// Check the HomeController after hitting the Send button from the HomeController, by adding the debugger.
// URL in the Postman must have the /number/true to run the action method because thats what we have added in our
// Route attribute. E.g. YourURl/bookstore/1/true 
// And pass bookid 20 and author YourName in the body(x-www-form-urlencoded) of the postman.
// It seems that letters should match with the parameters in the method or to Route Attribute area:
// of Query String Parameter or Route Data which we send in URL using ?key=valye&key=value or /value/value
// Where key name should match with the parameter name in the action method or the Property names of the Model class.
// Same case is for form-urlencoded. 
// Its okay if they are not Case-sensitive. Only thing is to match the letters.
// Postman shuld be set the POST.
