// Adding validations for each in action methods makes it dirty, lets see how to do that in the Model class.
// In case of model validations, you will be writing the validation rules as
// attributes i.e. [Attribute[ just above the properties in the model class.
// So that it reflects the meaning that this particular property should satisfy this particular
// rule. For example, if you add an attribute called required 
// that indicates that that property cannot be null or empty. So in case if the null value or empty
// value is submitted as a part of the request, then it is treated as a validation error.
// And there is a possibility of detecting the validation errors and sending the error messages
// to the user as a part of the response.
// Check the HomeController and Person class Model.
// Run your URL + /register in the postman with POST action.
// In the Postman Body->form-data -> Add your all key value pairs which are present in the Model class
// as properties.
// Even though we have added the [Required] attribute in the Model class name property,
// when we send null value from postman, we get the data in the action method person object parameter.
// So, there is a validation error but action method's return type content() will always return a positive 
// response. So, we will check how to accept that validation error in the next lecture.

