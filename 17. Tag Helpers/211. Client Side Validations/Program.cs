By default, the client-side validations are not enabled in ASP.NET Core applications.
If you want, you have to enable it manually.

These are the three steps to perform the client-side validations
that is data annotations, data store attributes, and importing the jQuery validation scripts.
The first step is adding the data annotations on the model properties.
Through data annotation attributes, you can specify the validation rules in the model class itself.

For example, if you have a look at the PersonAddRequest,
we have already enabled the client-side validations
with required range, email address,
already you know how to apply the validation roles for the model properties.

2nd data store attributes:
These are automatically generated when you are using the tag helper called ASP-for.
For e.g. for one property you have added the "required" atribute in the PersonAddRequest.
Then when you use asp-for in html, the "data-required" attribute with your given message in the controller attribute 
is added in the html. It will also add data-val="true" in html in this case of "Required" attribute.
data-val="true" means mandatory.And also data-required equal to the actual error message
that you apply on required attribute.


Now for 3rd we need JQuery validation scripts.
That is, at first, we have to load jQuery.js file
and then jQuery.validate.unobtrusive.js file.
Each of these files is dependent on the previous one.
That is, the first file is the regular jQuery file.
As you may know already, the jQuery is one of the third-party scripts
that provides the shortcut functions to perform the DOM manipulations in browser.
But however, for the validation perspective,
you are not writing any jQuery code, but you have to import the jQuery file.
Because the second file, that is, jQuery.validate.js file
works based on jQuery.js file.


All right, then what is this jQuery.validate.js file will do is that
it provides validation capabilities for the existing jQuery functions.
That means it is able to check the values of the textboxes when the user clicks on the submit button
and also when the user types something in the textbox, it can validate.
And based on that, it may show or hide the error messages.
Means if the value is valid, the error message will be hidden.
But in case if the value is invalid, that error message can be shown. 
That functionality is provided by jQuery.validate.js.


But the problem is, there is no direct connection between the data attributes and jQuery.validate.js.
Means the jQuery.validate.js file cannot read the data store attributes
and cannot perform the validations based on that.
So to bridge them, you require another file called jQuery.validate.unobtrusive.js.
The general meaning of unobtrusive is that, without modifying the source.
That means you are providing the validation functionality on the existing input tags
without modifying them.
So what this jQuery.validate. unobtrusive.js file will do is that,
it automatically reads the data store attributes of the input tag
that are generated by asp-for tag helper.
Accordingly, the appropriate validation error messages will be supplied to the jQuery.validate.js file.
So that it can hide or show error messages whenever needed.

