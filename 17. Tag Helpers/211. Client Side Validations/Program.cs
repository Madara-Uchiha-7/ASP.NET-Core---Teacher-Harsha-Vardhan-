But the browser makes another request to the mentioned URL.


As a result of CDN, you will get the benefit of cross-site caching.
That means on the browser perspective,
when the site is opened for the first time,
this jquery file gets cached in the browser memory.
But when you're opening another page that sends requests to the same URL,
that means it also uses the same CDN link.
Instead of reloading the same file one more time from this CDN link,
it uses the cached version of the same file.

