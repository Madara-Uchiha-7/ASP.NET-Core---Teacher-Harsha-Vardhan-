/*
There is a drawback on CDN. You cannot rely on CDN always.
which we used in the last lecture.
In case if there is a downside on CDN site, your application may not work.
To overcome this problem, it is advisable to maintain a fallback URL.
Means, if the file is not loaded into the browser for some reason,
then your local file should load.
To make it possible, we have tag helpers for script.
You can mention the fallback source by using this ASP fallback src.:

<script src="CDNUrl" asp-fallback-src="~/LoadUrl" asp-fallback-test="object" ></sciprt>
The above will become as :->
<script src="CDNUrl"></sciprt>
<script>object || document.write("<script scr='/LoadUrl'></script>");</script>

asp-fallback-test="object" here we check if we got undefied as a result or not
if yes then we are saying, goto ulr mentioned in asp-fallback-src="~/LoadUrl"
Here we are passing the local url where jquery and others are present.
For this we need it downloaded in our local machine, we just go to mentioned url in the src tag i.e.:

https://cdnjs.cloudflare.com/ajax/libs/jquery/3.6.0/jquery.min.js
https://cdnjs.cloudflare.com/ajax/libs/jquery-validate/1.19.4/jquery.validate.min.js
https://cdnjs.cloudflare.com/ajax/libs/jquery-validation-unobtrusive/3.2.12/jquery.validate.unobtrusive.min.js

So, when you paste this link to download the package,
you will get some code on the browser,
click control + s, save the file somewhere in your machine,
do this for each one.

We have kept all 3 files in our wwwroot folder needed for ASP.NET Core

We have used:
asp-fallback-test="window.jQuery"
asp-fallback-test="window.jQuery.validator"
asp-fallback-test="window.jQuery.validator.unobtrusive"

"window.jQuery", "window.jQuery.validator", "window.jQuery.validator.unobtrusive"
these are the object names.

Run the app, click on create person button,
goto elements tab,
search for our script tag
there you will find another script tag,
which has a code in it. That code is generated but our tag helper.

Adding this another local link or an additional link so that if main link fails then 
we have have something as backup is known as the fallback scripts.

It is recommended to not add the script tags as a part of the div tag.
It is recommented to add them at the most bottom of the body tag.
Since we are using the partial view, that view is getting loaded in the _Layout view's RenderBody()
which is not at the botton of the body tag. So our scripts are getting loaded in the middle of the body tag.


In order to fix that, we can use the layout view sections.
Thats why you will see our scripts inside the @section scripts{} in the create view.

And then 
we have used that section at the end of the <body> tag of the _Layout View.
We wrote :
@RenderSection("scripts", required: false)

required: false means
in case if some views doesn't provide this particular script,
it will be ignored. It will not be errored.

You can check this in the element tab in the inspect mode.

Alternatively, if you place the script tags or CSS files directly in your own application folder,
then you need not maintain any fallback URL.

There are few more additional script tags which are generated by Visual Studio
that is related to browser link
which enables the page to refresh automatically as soon as you make any changes in the code.
For example, you make any changes in the view,
the page gets refreshed in the browser.

That is the functionality of the browser link. 
That code you will find in inspect mode's element tab's <!-- Visual Studio Browser Link --> area in the html page.
It is provided by Visual Studio automatically.

